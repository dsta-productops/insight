import type { SessionMeta, TranscriptDoc } from "@/lib/transcribe/types";
import type { SuggestionLogEntry } from "@/lib/suggest/log";
import type { SummaryDoc } from "@/lib/summary";
import { getMode } from "@/lib/modes/registry";
import { stripListMarker } from "@/lib/utils";

/**
 * Session export shapes. Both the JSON and the Markdown are built here and kept
 * deliberately clean/structured so they can later be filed into CLARA (the
 * Confluence research assistant) without reshaping. Do NOT build the CLARA
 * integration here — just keep the export faithful.
 */

export interface SessionExport {
  session: SessionMeta;
  transcript: TranscriptDoc | null;
  /** Running conversation summary captured during/after the session, if any. */
  summary: { updatedAt: string; bullets: string[] } | null;
  /** Flattened, time-anchored coach activity (offset seconds from start). */
  coachActivity: {
    atSec: number | null;
    at: string;
    provider: string;
    query: string;
    type: string;
    title: string;
    ask: string;
    body: string;
    why: string;
    source: string;
    confidence: number;
  }[];
}

function mmss(sec: number): string {
  const m = Math.floor(sec / 60);
  const s = Math.floor(sec % 60);
  return `${m.toString().padStart(2, "0")}:${s.toString().padStart(2, "0")}`;
}

/** Offset in seconds of a wall-clock instant from the transcript start. */
function offsetSec(at: string, transcript: TranscriptDoc | null): number | null {
  if (!transcript) return null;
  const t0 = Date.parse(transcript.createdAt);
  if (!Number.isFinite(t0)) return null;
  const lastEnd = transcript.segments.at(-1)?.end ?? 0;
  return Math.min(Math.max((Date.parse(at) - t0) / 1000, 0), lastEnd);
}

export function buildSessionExport(
  session: SessionMeta,
  transcript: TranscriptDoc | null,
  suggestions: SuggestionLogEntry[],
  summary: SummaryDoc | null,
): SessionExport {
  const coachActivity = suggestions.flatMap((entry) =>
    entry.suggestions.map((s) => ({
      atSec: offsetSec(entry.at, transcript),
      at: entry.at,
      provider: entry.provider,
      query: entry.query,
      type: s.type,
      title: s.title,
      ask: s.ask,
      body: s.body,
      why: s.why,
      source: s.source,
      confidence: s.confidence,
    })),
  );
  coachActivity.sort((a, b) => (a.atSec ?? 0) - (b.atSec ?? 0));
  return {
    session,
    transcript,
    summary: summary
      ? { updatedAt: summary.updatedAt, bullets: summary.bullets }
      : null,
    coachActivity,
  };
}

const SPEAKER_LABEL: Record<string, string> = {
  researcher: "Researcher",
  participant: "Participant",
};

export function toMarkdown(data: SessionExport): string {
  const { session, transcript, summary, coachActivity } = data;
  const lines: string[] = [];

  lines.push(`# ${session.title}`, "");
  lines.push(`- **Source:** ${session.filename}`);
  lines.push(`- **Recorded:** ${new Date(session.uploadedAt).toLocaleString()}`);
  if (session.durationSec) lines.push(`- **Duration:** ${mmss(session.durationSec)}`);
  lines.push(`- **Transcription:** ${session.provider}`);
  if (transcript?.labeledAt) {
    lines.push(`- **Speakers labeled:** ${new Date(transcript.labeledAt).toLocaleString()}`);
  }
  lines.push("", "> Generated by INSIGHT.", "");

  if (summary && summary.bullets.length > 0) {
    lines.push("## Recap", "");
    for (const b of summary.bullets) lines.push(`- ${stripListMarker(b)}`);
    lines.push("");
  }

  lines.push("## Transcript", "");
  if (transcript && transcript.segments.length > 0) {
    let lastSpeaker: string | undefined;
    for (const seg of transcript.segments) {
      const stamp = mmss(seg.start);
      if (seg.speaker && seg.speaker !== lastSpeaker) {
        lines.push("", `**${SPEAKER_LABEL[seg.speaker] ?? seg.speaker}**`);
        lastSpeaker = seg.speaker;
      }
      lines.push(`\`${stamp}\` ${seg.text}`);
    }
  } else {
    lines.push("_No transcript._");
  }
  lines.push("");

  lines.push("## Coach activity", "");
  if (coachActivity.length > 0) {
    for (const c of coachActivity) {
      const stamp = c.atSec != null ? `~${mmss(c.atSec)}` : "-";
      const lead = c.ask ? `"${c.ask}"` : c.body;
      lines.push(`- \`${stamp}\` **[${c.type}] ${c.title}**: ${lead}`);
      if (c.why || c.source) {
        lines.push(`  - _${[c.why, c.source].filter(Boolean).join(" · ")}_`);
      }
    }
  } else {
    lines.push("_No coach activity logged._");
  }
  lines.push("");

  return lines.join("\n");
}

/**
 * Recap-only Markdown download for the session review page. Serializes the
 * detailed theme-clustered recap (`sections`), falling back to the flat
 * `bullets` when no detailed recap exists. A focused artifact you can hand off
 * without the full transcript and coach log.
 */
export function recapToMarkdown(session: SessionMeta, summary: SummaryDoc): string {
  const lines: string[] = [];
  lines.push(`# ${session.title} - Recap`, "");
  const modeLabel = getMode(session.mode)?.label;
  if (modeLabel) lines.push(`- **Mode:** ${modeLabel}`);
  lines.push(`- **Recorded:** ${new Date(session.uploadedAt).toLocaleString()}`);
  lines.push("", "> Generated by INSIGHT.", "");

  if (summary.sections && summary.sections.length > 0) {
    for (const sec of summary.sections) {
      lines.push(`## ${sec.title}`, "");
      for (const p of sec.points) lines.push(`- ${stripListMarker(p)}`);
      lines.push("");
    }
  } else if (summary.bullets.length > 0) {
    lines.push("## Recap", "");
    for (const b of summary.bullets) lines.push(`- ${stripListMarker(b)}`);
    lines.push("");
  } else {
    lines.push("_No recap yet._", "");
  }

  return lines.join("\n");
}
